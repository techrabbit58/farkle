import pytest

import farkle


@pytest.mark.parametrize("roll, residual, expected_score", [
    ([1, 2, 3, 4, 5, 6], [], 1200),
    ([2, 2, 3, 3, 5, 5], [], 800),
    ([1, 1, 4, 4, 6, 6], [], 800),
    ([1, 3, 2, 3, 2, 1], [], 800),
    ([1, 1, 1, 1, 1, 1], [], 8000),
    ([2, 2, 2, 2, 2, 2], [], 1600),
    ([3, 3, 3, 3, 3, 3], [], 2400),
    ([4, 4, 4, 4, 4, 4], [], 3200),
    ([5, 5, 5, 5, 5, 5], [], 4000),
    ([6, 6, 6, 6, 6, 6], [], 4800),
    ([1, 1, 1, 1, 1, 2], [2], 4000),
    ([4, 2, 2, 2, 2, 2], [4], 800),
    ([3, 3, 3, 3, 3], [], 1200),
    ([5, 5, 3, 5, 5, 5], [3], 2000),
    ([1, 1, 1, 1, 2, 3], [2, 3], 2000),
    ([6, 2, 6, 6, 6], [2], 1200),
    ([5, 5, 5, 5], [], 1000),
    ([1, 1, 1, 2, 3, 4], [2, 3, 4], 1000),
])
def test_score_one_roll(roll, residual, expected_score):
    score, *remaining = farkle.best_score(roll)
    assert score == expected_score and remaining == residual
